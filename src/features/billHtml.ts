export type HtmlCtx = {
  lang: Lang;
  money: (v: number) => string;
  qty: (v: number) => string;
  num: (v: number, fractionDigits?: number) => string;
  shop: Shop | null;
};

function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

